import fs from 'node:fs';
import assert from 'node:assert/strict';
const ui=fs.readFileSync(new URL('../src/main.jsx',import.meta.url),'utf8');
const engine=fs.readFileSync(new URL('../src/engine.js',import.meta.url),'utf8');
const assignment=ui.match(/<div className="tactical-assignment-grid">([\s\S]*?)<div className="tactical-summary">/);
assert.ok(assignment,'tactical assignment grid exists');
assert.match(assignment[1],/선수 선택/,'player selector exists');
assert.match(assignment[1],/세부포지션/,'detail position selector exists');
assert.doesNotMatch(assignment[1],/slotPositionOptions/,'redundant broad position selector removed');
assert.ok(assignment[1].indexOf('선수 선택') < assignment[1].indexOf('세부포지션'),'player selector precedes detail position selector');
assert.doesNotMatch(engine,/type:'실점',options:\['빠른 교체 및 압박 강화'/,'conceding no longer triggers forced quick-response prompt');
assert.match(ui,/감독 전술 변경 · 압박/,'in-match tactical changes are recorded');
assert.match(ui,/setLiveMatch\(old=>old\?\(\{\.\.\.old,opts:/,'live match tactical options update when tactics change');
console.log('Lineup and live match management regression passed');
